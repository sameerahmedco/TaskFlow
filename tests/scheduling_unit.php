<?php
/** TaskFlow 1.14.0: custom workdays, partial-day leave and holiday math. */
declare(strict_types=1);
require_once __DIR__ . '/../includes/scheduling.php';
$n=0;$bad=0;
$check=function(bool $test,string $name)use(&$n,&$bad){$n++;if(!$test){$bad++;fwrite(STDERR,"FAIL $name\n");}else echo "PASS $name\n";};
$reject=function(callable $fn){try{$fn();return false;}catch(InvalidArgumentException){return true;}};
$weekStart='2026-11-16';$weekEnd='2026-11-22';
$availability=fn(int $minutes,int $mask,array $leave=[],array $holiday=[])=>
    taskflow_schedule_availability($minutes,$mask,$leave,$holiday,$weekStart,$weekEnd);
$full=['start_date'=>'2026-11-16','end_date'=>'2026-11-20','day_portion'=>'full'];
$halfAM=['start_date'=>'2026-11-17','end_date'=>'2026-11-17','day_portion'=>'am'];
$halfPM=['start_date'=>'2026-11-17','end_date'=>'2026-11-17','day_portion'=>'pm'];
$check(taskflow_schedule_mask(31)===31,'weekday default');
$check(taskflow_schedule_mask(64)===64,'Sunday workday accepted');
$check($reject(fn()=>taskflow_schedule_mask(0)),'no workdays rejected');
$check($reject(fn()=>taskflow_schedule_mask(128)),'mask overflow rejected');
$check($reject(fn()=>taskflow_schedule_mask('1.5')),'mask fractional rejected');
$check(taskflow_leave_portion('am')==='am','morning portion accepted');
$check($reject(fn()=>taskflow_leave_portion('quarter')),'unrecognized portion rejected');
$check(!taskflow_leave_portion_valid('2026-11-17','2026-11-18','am'),'half-day must use one date');
$check(taskflow_leave_portion_valid('2026-11-17','2026-11-17','pm'),'single afternoon accepted');
$check($availability(2400,31)['effective_capacity_minutes']===2400,'weekday baseline preserved');
$check($availability(2400,31,[$halfAM])['effective_capacity_minutes']===2160,'half-day deducts four of forty hours');
$check($availability(2400,31,[$halfAM,$halfPM])['approved_leave_days']===1.0,'two distinct halves count as full day');
$check($availability(2400,31,[$halfAM,$halfPM])['effective_capacity_minutes']===1920,'two halves deduct eight hours');
$check($availability(2400,31,[$halfAM,$halfAM])['approved_leave_days']===0.5,'overlapping half is not double-counted');
$check($availability(2400,31,[$full])['effective_capacity_minutes']===0,'full working week zero availability');
$check($availability(2400,31,[$halfAM],['2026-11-17'])['effective_capacity_minutes']===1920,'holiday supersedes overlapping half-day');
$check($availability(2400,31,[],['2026-11-21'])['holiday_days']===0,'weekend holiday has no effect for weekday worker');
$check($availability(2400,31,[],['2026-11-19','2026-11-19'])['holiday_days']===1,'duplicate holiday dates are not double-counted');
$check($availability(2000,30,[],['2026-11-16'])['effective_capacity_minutes']===2000,'Monday holiday does not affect Tue-Fri worker');
$check($availability(1400,65,[],['2026-11-22'])['effective_capacity_minutes']===700,'Sunday holiday affects Mon+Sun worker');
$check($availability(600,64,[$halfAM])['effective_capacity_minutes']===600,'leave outside scheduled workdays ignored');
$check($availability(600,64,[['start_date'=>'2026-11-22','end_date'=>'2026-11-22','day_portion'=>'pm']])['effective_capacity_minutes']===300,'Sunday half-day counted on Sunday schedule');
$check($reject(fn()=>taskflow_schedule_availability(2400,31,[],[],'2026-11-17','2026-11-23')),'non-Monday week rejected');
$check($reject(fn()=>taskflow_holiday_title("bad\0title")),'holiday null byte rejected');
$check($reject(fn()=>taskflow_holiday_title(str_repeat('x',101))),'oversized holiday rejected');
$check(taskflow_holiday_title('  Founders Day ')==='Founders Day','holiday title trimmed');
$check(taskflow_holiday_year('2026',2026)===2026,'year allowed');
$check($reject(fn()=>taskflow_holiday_year(2030,2026)),'distant year rejected');
$check($reject(fn()=>taskflow_holiday_year('2026; DROP',2026)),'invalid year rejected');
if($bad) exit(1);
echo "All $n scheduling checks passed.\n";
