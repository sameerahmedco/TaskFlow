<?php
/** TaskFlow 1.13.0: strict UTC leave validation and availability calculations. */
require_once __DIR__ . '/../includes/time_off.php';
$total=0;$failed=0;
$check=function(bool $ok,string $name)use(&$total,&$failed){$total++;if(!$ok){$failed++;fwrite(STDERR,"FAIL $name\n");}else echo "PASS $name\n";};
$now=new DateTimeImmutable('2026-11-16T15:00:00Z');
$range=fn($a,$b)=>taskflow_time_off_range($a,$b,$now);
$check($range('2026-11-16','2026-11-16')['days']===1,'one-day request accepted');
$check($range('2026-11-16','2026-11-20')['days']===5,'five-day request accepted');
$check($range('2026-02-30','2026-03-01')===null,'invalid date rejected');
$check($range('2026-11-25','2026-11-24')===null,'reversed dates rejected');
$check($range('2026-11-16','2027-01-16')===null,'unbounded spans rejected');
$check($range('2026-10-16','2026-10-17')===null,'past-window bound');
$check($range('2027-11-17','2027-11-17')===null,'future-window bound');
$check($range('2026-11-16','2026-12-30')!==null,'45-day request accepted');
$check(taskflow_time_off_date('2026-11-16extra')===null,'suffix rejected');
$check(taskflow_time_off_date('2026-11-16')!==null,'UTC date parsed');
$check(taskflow_time_off_note('  Personal appointment  ')==='Personal appointment','note trimmed');
$rejects=function(callable $fn){try{$fn();return false;}catch(InvalidArgumentException){return true;}};
$check($rejects(fn()=>taskflow_time_off_note("unsafe\0note")),'null byte rejected');
$check($rejects(fn()=>taskflow_time_off_note(str_repeat('x',301))),'oversize note rejected');
$week=['2026-11-16','2026-11-22'];
$days=fn($ranges)=>taskflow_time_off_weekdays($ranges,...$week);
$check($days([])===0,'no leave days');
$check($days([['start_date'=>'2026-11-16','end_date'=>'2026-11-20']])===5,'five weekdays counted');
$check($days([['start_date'=>'2026-11-21','end_date'=>'2026-11-22']])===0,'weekends excluded');
$check($days([['start_date'=>'2026-11-19','end_date'=>'2026-11-25']])===2,'week clipping');
$check($days([['start_date'=>'2026-11-16','end_date'=>'2026-11-18'],['start_date'=>'2026-11-18','end_date'=>'2026-11-20']])===5,'overlaps counted once');
$check(taskflow_time_off_effective_capacity(2400,2)===1440,'two off days remove sixteen hours');
$check(taskflow_time_off_effective_capacity(2400,5)===0,'full week removes capacity');
$check(taskflow_time_off_effective_capacity(600,0)===600,'baseline preserved');
$check($rejects(fn()=>taskflow_time_off_effective_capacity(5000,1)),'invalid capacity rejected');
$check($rejects(fn()=>taskflow_time_off_weekdays([], '2026-11-16','2026-11-30')),'unbounded week rejected');
if($failed) exit(1);
echo "All $total time-off checks passed.\n";
